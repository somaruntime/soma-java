    private static void appendFieldEndpoint(
            StringBuilder source,
            CompositionModel.FieldModel field,
            int fieldIndex) {
        source.append("    public final class ").append(fieldType(field))
                .append(" implements io.github.somaruntime.soma.SomaKeyableField<")
                .append("View, java.lang.Long> {\n\n")
                .append("        private ").append(fieldType(field)).append("() {\n")
                .append("        }\n\n");
        appendComparison(source, "eq", fieldIndex);
        appendComparison(source, "ne", fieldIndex);
        appendComparison(source, "lt", fieldIndex);
        appendComparison(source, "le", fieldIndex);
        appendComparison(source, "gt", fieldIndex);
        appendComparison(source, "ge", fieldIndex);
        source.append("        public io.github.somaruntime.soma.SomaExpression<View> between(\n")
                .append("                long lowerInclusive,\n")
                .append("                long upperInclusive) {\n")
                .append("            return runtime.between(").append(fieldIndex)
                .append(", lowerInclusive, upperInclusive);\n")
                .append("        }\n\n")
                .append("        public io.github.somaruntime.soma.SomaExpression<View> ")
                .append("in(long... values) {\n")
                .append("            return runtime.in(").append(fieldIndex).append(", values);\n")
                .append("        }\n")
                .append("    }\n\n");
    }

    private static void appendComparison(
            StringBuilder source,
            String name,
            int fieldIndex) {
        source.append("        public io.github.somaruntime.soma.SomaExpression<View> ")
                .append(name)
                .append("(long value) {\n")
                .append("            return runtime.").append(name).append('(')
                .append(fieldIndex).append(", value);\n")
                .append("        }\n\n");
    }

    private static StringBuilder header(CompositionModel model, int capacity) {
        return new StringBuilder(capacity)
                .append("// Generated by SOMA. Do not edit.\n")
                .append("package ").append(model.generatedPackage()).append(";\n\n");
    }

    private static void appendParameters(
            StringBuilder source,
            List<CompositionModel.FieldModel> fields) {
        for (int index = 0; index < fields.size(); index++) {
            if (index != 0) {
                source.append(", ");
            }
            source.append("long ").append(fields.get(index).name());
        }
    }

    private static void appendObjectReads(
            StringBuilder source,
            List<CompositionModel.FieldModel> fields,
            String receiver) {
        for (int index = 0; index < fields.size(); index++) {
            if (index != 0) {
                source.append(", ");
            }
            source.append(receiver).append('.').append(fields.get(index).name()).append("()");
        }
    }

    private static void appendMethodReads(
            StringBuilder source,
            List<CompositionModel.FieldModel> fields,
            String receiver) {
        appendObjectReads(source, fields, receiver);
    }

    private static void appendArrayReads(
            StringBuilder source,
            int fieldCount,
            String receiver) {
        for (int index = 0; index < fieldCount; index++) {
            if (index != 0) {
                source.append(", ");
            }
            source.append(receiver).append('[').append(index).append(']');
        }
    }

    private static String fieldType(CompositionModel.FieldModel field) {
        return GeneratedNames.fieldEndpointType(field.name());
    }

    private static String renderManifest(
            CompositionModel model,
            List<RenderedSource> sources) {
        StringBuilder manifest = new StringBuilder(1400);
        appendProperty(manifest, "format", "1");
        appendProperty(manifest, "schema.package", model.schemaPackage());
        appendProperty(manifest, "generated.package", model.generatedPackage());
        appendProperty(manifest, "processor.version", model.processorVersion());
        appendProperty(manifest, "contract.version", model.contractVersion());
        appendProperty(manifest, "runtime.build.sha256", model.runtimeBuildIdentity());
        appendProperty(manifest, "fingerprint.sha256", model.fingerprint());
        StringBuilder generatedFiles = new StringBuilder();
        for (RenderedSource source : sources) {
            if (generatedFiles.length() != 0) {
                generatedFiles.append(',');
            }
            generatedFiles.append(source.typeName);
        }
        appendProperty(manifest, "generated.files", generatedFiles.toString());
        appendProperty(manifest, "schema.line.count",
                Integer.toString(model.schemaLines().size()));
        List<String> lines = model.schemaLines();
        for (int index = 0; index < lines.size(); index++) {
            appendProperty(manifest, "schema.line." + index, lines.get(index));
        }
        return manifest.toString();
    }

    private static void appendProperty(
            StringBuilder target,
            String key,
            String value) {
        target.append(key).append('=');
        for (int index = 0; index < value.length(); index++) {
            char character = value.charAt(index);
            switch (character) {
                case '\\':
                    target.append("\\\\");
                    break;
                case '\t':
                    target.append("\\t");
                    break;
                case '\n':
                    target.append("\\n");
                    break;
                case '\r':
                    target.append("\\r");
                    break;
                case '\f':
                    target.append("\\f");
                    break;
                default:
                    if (character < 0x20 || character > 0x7e) {
                        target.append("\\u");
                        String hex = Integer.toHexString(character);
                        for (int padding = hex.length(); padding < 4; padding++) {
                            target.append('0');
                        }
                        target.append(hex);
                    } else {
                        target.append(character);
                    }
                    break;
            }
        }
        target.append('\n');
    }

    static final class RenderedComposition {

        private final CompositionModel model;
        private final List<RenderedSource> sources;
        private final String manifest;

        private RenderedComposition(
                CompositionModel model,
                List<RenderedSource> sources,
                String manifest) {
            this.model = model;
            this.sources = sources;
            this.manifest = manifest;
        }
    }

    private static final class RenderedSource {

        private final String typeName;
        private final String source;

        private RenderedSource(String typeName, String source) {
            this.typeName = typeName;
            this.source = source;
        }
    }
