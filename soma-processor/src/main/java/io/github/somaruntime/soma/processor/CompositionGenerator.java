    private static void appendViewAndEditor(
            StringBuilder source,
            CompositionModel model,
            CompositionModel.TableModel table) {
        String objectType = model.generatedPackage() + "." + table.simpleName();
        source.append("    public static class View {\n\n")
                .append("        private final io.github.somaruntime.soma.internal")
                .append(".LongEditorSession session;\n\n")
                .append("        private View(io.github.somaruntime.soma.internal")
                .append(".LongEditorSession session) {\n")
                .append("            this.session = session;\n")
                .append("        }\n\n");
        for (int index = 0; index < table.fields().size(); index++) {
            CompositionModel.FieldModel field = table.fields().get(index);
            source.append("        public long ").append(field.name()).append("() {\n")
                    .append("            return session.value(").append(index).append(");\n")
                    .append("        }\n\n");
        }
        source.append("        public ").append(objectType).append(" fetch() {\n")
                .append("            return new ").append(objectType).append('(');
        appendMethodReads(source, table.fields(), "this");
        source.append(");\n")
                .append("        }\n")
                .append("    }\n\n")
                .append("    public static final class Editor extends View {\n\n")
                .append("        private final io.github.somaruntime.soma.internal")
                .append(".LongEditorSession session;\n\n")
                .append("        private Editor(io.github.somaruntime.soma.internal")
                .append(".LongEditorSession session) {\n")
                .append("            super(session);\n")
                .append("            this.session = session;\n")
                .append("        }\n\n")
                .append("        private static Editor create(")
                .append("io.github.somaruntime.soma.internal.LongEditorSession session) {\n")
                .append("            return new Editor(session);\n")
                .append("        }\n\n");
        for (int index = 0; index < table.fields().size(); index++) {
            CompositionModel.FieldModel field = table.fields().get(index);
            if (field.role() != CompositionModel.FieldRole.KEY) {
                source.append("        public void ").append(field.name())
                        .append("(long value) {\n")
                        .append("            session.value(").append(index).append(", value);\n")
                        .append("        }\n\n");
            }
        }
        source.append("        @java.lang.Override\n")
                .append("        public ").append(objectType).append(" fetch() {\n")
                .append("            return super.fetch();\n")
                .append("        }\n")
                .append("    }\n\n");
    }

